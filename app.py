import streamlit as st
import numpy as np
from keras.models import load_model
from keras.preprocessing import image
import gdown
import os

# download model if not available
if not os.path.exists("scene_model.h5"):
    url = "https://drive.google.com/uc?id=18vYalPqYASGaxgS4eZLiZypk-4Z-TwEw"
    gdown.download(url, "scene_model.h5", quiet=False)

# load model
model = load_model("scene_model.h5")

class_names = ['buildings', 'forest', 'glacier', 'mountain', 'sea', 'street']

st.title("Natural Scene Classification")

file = st.file_uploader("Upload image", type=["jpg","png","jpeg"])

if file is not None:
    img = image.load_img(file, target_size=(100,100))
    img_array = image.img_to_array(img)/255.0
    img_array = np.expand_dims(img_array, axis=0)

    pred = model.predict(img_array)

    st.image(file)
    st.write("Prediction:", class_names[np.argmax(pred)])

