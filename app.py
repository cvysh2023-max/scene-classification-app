import streamlit as st
import numpy as np
from tensorflow.keras.models import load_model
from tensorflow.keras.preprocessing import image
import gdown
import os

# download model from Google Drive if not present
if not os.path.exists("scene_model.h5"):
    url = "https://drive.google.com/uc?id=1B1DXQnYtruQCh6auof-J5pR89PXxiPG3"
    gdown.download(url, "scene_model.h5", quiet=False)

# load model safely (important fix ✅)
if os.path.exists("scene_model.h5"):
    model = load_model("scene_model.h5", compile=False)
else:
    st.error("Model file not found. Check Google Drive link.")

# class labels
class_names = ['buildings', 'forest', 'glacier', 'mountain', 'sea', 'street']

# app title
st.title("Natural Scene Classification")

# upload image
uploaded_file = st.file_uploader("Upload an image", type=["jpg", "jpeg", "png"])

if uploaded_file is not None:

    # load and preprocess image
    img = image.load_img(uploaded_file, target_size=(100,100))
    img_array = image.img_to_array(img) / 255.0
    img_array = np.expand_dims(img_array, axis=0)

    # make prediction
    prediction = model.predict(img_array)
    pred_index = np.argmax(prediction)

    # display result
    st.image(uploaded_file, caption="Uploaded Image")
    st.write("Predicted Scene:", class_names[pred_index])

